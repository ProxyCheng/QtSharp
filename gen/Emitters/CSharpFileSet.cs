using System;
using System.Collections.Generic;
using System.Text;

namespace QtSharp.Generator
{
    /// <summary>
    /// The C# files one run builds, keyed by their path below <c>generated/</c>. The preamble and
    /// namespace are opened once per file; the emitter that adds a declaration does not repeat
    /// them. The set is handed to the output only when the run completes.
    /// </summary>
    public sealed class CSharpFileSet
    {
        private readonly Dictionary<string, StringBuilder> files = new(StringComparer.Ordinal);
        private readonly string ns;
        private readonly string modelFileName;

        public CSharpFileSet(string ns, string modelFileName)
        {
            this.ns = ns;
            this.modelFileName = modelFileName;
        }

        /// <summary>The file for a header, mirroring how the C++ headers are split.</summary>
        public static string HeaderKey(string header)
        {
            string path = (header ?? string.Empty).Replace('\\', '/');
            if (path.EndsWith(".h", StringComparison.OrdinalIgnoreCase))
                path = path.Substring(0, path.Length - 2);
            if (path.Length == 0)
                path = "misc";
            return path + ".cs";
        }

        public static string PlainKey(string name) => name + ".cs";

        public StringBuilder File(string key)
        {
            if (files.TryGetValue(key, out var text))
                return text;
            text = new StringBuilder();
            text.AppendLine($"// <auto-generated> generated from {modelFileName} - do not edit");
            text.AppendLine("using System;");
            text.AppendLine("using QtSharp.Runtime;   // handles, signals and the marshalling runtime");
            text.AppendLine("using System.CodeDom.Compiler;   // [GeneratedCode] on every wrapper type");
            text.AppendLine("using System.Collections.Generic;");
            text.AppendLine("using System.Runtime.CompilerServices;");
            text.AppendLine("using System.Runtime.InteropServices;");
            text.AppendLine("using System.Security;");
            text.AppendLine("#pragma warning disable 660, 661, 0649   // generated fields a hierarchy may not use");
            text.AppendLine();
            text.AppendLine($"namespace {ns}");
            text.AppendLine("{");
            files.Add(key, text);
            return text;
        }

        public void Save(OutputFileSet output)
        {
            foreach (var pair in files)
            {
                pair.Value.AppendLine("}");
                output.Add(pair.Key, pair.Value.ToString());
            }
        }
    }
}
