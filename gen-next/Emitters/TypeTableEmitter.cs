using System;
using System.IO;

namespace QtSharp.Generator
{
    /// <summary>
    /// Emits the assembly's C#-to-Qt metatype table: only the types this run publishes, so a
    /// dependency's types stay in its own assembly and its own initializer.
    /// </summary>
    public sealed class TypeTableEmitter : Emitter
    {
        public TypeTableEmitter(GeneratorContext context) : base(context)
        {
        }

        public override void Emit()
        {
            string ns = Context.Model.Namespace ?? "QtSharp.Api";
            var binding = Context.Binding;
            var w = Context.Output.File($"{ns}.TypeTable.cs");

            w.Line($"// <auto-generated> generated from {Path.GetFileName(Context.Model.Path)} - do not edit");
            w.Line("using System;");
            w.Line("using QtSharp.Runtime;   // handles, signals and the marshalling runtime");
            w.Line("using System.CodeDom.Compiler;   // [GeneratedCode] on every wrapper type");
            w.Line("using System.Collections.Generic;");
            w.Line("using System.Runtime.CompilerServices;");
            w.Line("using System.Runtime.InteropServices;");
            w.Line("using System.Security;");
            w.Line("#pragma warning disable 660, 661, 0649   // generated fields a hierarchy may not use");
            w.Line();
            w.Open($"namespace {ns}");
            w.Line("/// <summary>The Qt type names of the types this assembly publishes.</summary>");
            w.Open("internal static class BoundTypeTable");
            w.Line("[ModuleInitializer]");
            w.Open("internal static void Register()");

            foreach (var cls in binding.Classes)
            {
                string name = binding.Name(cls);
                // QVariant is the internal bridge; QChar/QUuid and runtime structs were already
                // filtered out of Classes (the structs register as Pod below).
                if (name == "QVariant")
                    continue;
                string kind = binding.DerivesFromQObject(binding.Ref(cls)) ? "ObjectPointer" : "ValueClass";
                w.Line($"QtSharp.Runtime.MetaType.Register(typeof({binding.CsTypeName(binding.Ref(cls))}), {Quote(binding.CppClass(name))}, QtSharp.Runtime.QtTypeKind.{kind});");
            }

            foreach (var s in ApiTypes.RuntimeStructs)
            {
                if (!binding.ModelRuntimeStructNames.Contains(s.Name))
                    continue;
                w.Line($"QtSharp.Runtime.MetaType.Register(typeof({s.Name}), {Quote(ApiTypes.CppStructName(s.Name))}, QtSharp.Runtime.QtTypeKind.Pod);");
            }

            foreach (var e in binding.Enums)
            {
                if (!binding.EnumIsEmitted(e))
                    continue;
                string qualified = e.GetProperty("qualified").GetString();
                string cpp = binding.CppEnumNames.TryGetValue(qualified, out var spelled) ? spelled : qualified;
                w.Line($"QtSharp.Runtime.MetaType.Register(typeof({binding.CsTypeName(qualified)}), {Quote(cpp)}, QtSharp.Runtime.QtTypeKind.Enum);");
            }

            w.Close();
            w.Close();
            w.Blank();
            w.Close();
        }

        private static string Quote(string text)
            => "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
    }
}
