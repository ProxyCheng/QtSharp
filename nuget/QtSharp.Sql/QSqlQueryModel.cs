using System;
using System.Collections.Generic;
using System.Data;
using System.Data.Common;
using QtSharp.QtCore;

namespace QtSharp.QtSql
{
    /// <summary>
    /// The C# counterpart of QtSql's <c>QSqlQueryModel</c>: a read-only
    /// <see cref="QAbstractTableModel"/> over a SQL result set, materialized through ADO.NET so the
    /// data survives the reader. Set a <see cref="DbConnection"/>, run a query, and pass the model
    /// to any Qt view - no Qt SQL module is involved.
    ///
    /// Values cross into Qt as <c>object</c> variants (the generated API takes <c>object</c>
    /// wherever Qt says QVariant); a NULL is an invalid variant, and the few ADO.NET types with no
    /// direct mapping (decimal, DateTimeOffset, TimeSpan) are converted.
    /// </summary>
    public class QSqlQueryModel : QAbstractTableModel
    {
        readonly List<string> columns = new();
        readonly List<object[]> rows = new();
        readonly List<bool> readOnlyColumns = new();
        readonly List<bool> autoColumns = new();
        readonly List<Dictionary<int, object>> headers = new();
        DbConnection connection;
        string lastQuery;
        Exception lastError;
        (string Name, object Value)[] lastParameters = Array.Empty<(string, object)>();

        public QSqlQueryModel()
        {
        }

        /// <summary>The connection the model reads from.</summary>
        protected DbConnection Connection => connection;

        /// <summary>The result set's column names, in SELECT order.</summary>
        public IReadOnlyList<string> Columns => columns;

        /// <summary>The index of a column name, or -1.</summary>
        protected int ColumnIndex(string name)
        {
            for (int i = 0; i < columns.Count; i++)
                if (string.Equals(columns[i], name, StringComparison.Ordinal))
                    return i;
            return -1;
        }

        /// <summary>
        /// Whether the provider reported the column as read-only (the ADO.NET schema table's
        /// IsReadOnly flag). SQLite reports no such flag, so every SQLite column stays editable -
        /// the same answer Qt's SQLite driver gives.
        /// </summary>
        protected bool IsColumnReadOnly(int column)
            => column >= 0 && column < readOnlyColumns.Count && readOnlyColumns[column];

        /// <summary>
        /// Whether the provider reported the column as auto-generated (an identity column), which
        /// is what an INSERT omits so the database assigns the value.
        /// </summary>
        protected bool IsColumnAutoGenerated(int column)
            => column >= 0 && column < autoColumns.Count && autoColumns[column];

        /// <summary>Sets the connection; call it before <see cref="SetQuery"/>.</summary>
        public void SetConnection(DbConnection connection)
            => this.connection = connection ?? throw new ArgumentNullException(nameof(connection));

        /// <summary>
        /// The exception behind the last failed <see cref="SetQuery"/>/<see cref="Select"/>, or null
        /// after a successful one - the counterpart of Qt's <c>lastError()</c>. A provider error is
        /// reported here rather than thrown, so the <c>bool</c> returns mean something, the way Qt
        /// keeps the driver's error in the model instead of unwinding it through its C++ frames.
        /// </summary>
        public Exception LastError() => lastError;

        /// <summary>Records a failure for <see cref="LastError"/>; a subclass reports its own.</summary>
        protected void SetLastError(Exception error) => lastError = error;

        /// <summary>
        /// Runs the query and replaces the model's rows. Parameters are ADO.NET named parameters
        /// (<c>@name</c>); a null value becomes DBNull.
        /// </summary>
        public bool SetQuery(string query, params (string Name, object Value)[] parameters)
        {
            if (connection == null)
                throw new InvalidOperationException("SetConnection must be called before SetQuery.");
            lastQuery = query ?? throw new ArgumentNullException(nameof(query));
            lastParameters = parameters ?? Array.Empty<(string, object)>();
            return Execute();
        }

        /// <summary>Runs the last query again.</summary>
        public bool Select() => lastQuery != null && Execute();

        /// <summary>Reloads the model (the counterpart of QSqlQueryModel::refresh).</summary>
        public void Refresh() => Select();

        bool Execute()
        {
            var newColumns = new List<string>();
            var newRows = new List<object[]>();
            var newReadOnly = new List<bool>();
            var newAuto = new List<bool>();

            try
            {
                if (connection.State != System.Data.ConnectionState.Open)
                    connection.Open();

                using var command = connection.CreateCommand();
                command.CommandText = lastQuery;
                foreach (var (name, value) in lastParameters)
                {
                    var parameter = command.CreateParameter();
                    parameter.ParameterName = name;
                    parameter.Value = value ?? DBNull.Value;
                    command.Parameters.Add(parameter);
                }

                using var reader = command.ExecuteReader();
                for (int i = 0; i < reader.FieldCount; i++)
                    newColumns.Add(reader.GetName(i));
                while (reader.Read())
                {
                    var row = new object[reader.FieldCount];
                    reader.GetValues(row);
                    newRows.Add(row);
                }
                ReadColumnFlags(reader, newReadOnly, newAuto);
            }
            catch (DbException exception)
            {
                // Qt's setQuery() replaces the query and resets the model even when the driver
                // rejects it: the rows are gone, lastError() says why, and nothing is thrown.
                ResetTo(new List<string>(), new List<object[]>(), new List<bool>(), new List<bool>());
                lastError = exception;
                return false;
            }

            lastError = null;
            ResetTo(newColumns, newRows, newReadOnly, newAuto);
            return true;
        }

        void ResetTo(List<string> newColumns, List<object[]> newRows,
            List<bool> newReadOnly, List<bool> newAuto)
        {
            BeginResetModel();
            columns.Clear();
            columns.AddRange(newColumns);
            rows.Clear();
            rows.AddRange(newRows);
            readOnlyColumns.Clear();
            readOnlyColumns.AddRange(newReadOnly);
            autoColumns.Clear();
            autoColumns.AddRange(newAuto);
            EndResetModel();
        }

        /// <summary>
        /// Reads the two per-column flags the schema table can carry (IsReadOnly, IsAutoIncrement).
        /// Providers are free not to offer it, and SQLite does not report IsReadOnly at all, so a
        /// missing table or column leaves every column editable and non-generated.
        /// </summary>
        static void ReadColumnFlags(DbDataReader reader, List<bool> readOnly, List<bool> autoIncrement)
        {
            for (int i = 0; i < reader.FieldCount; i++)
            {
                readOnly.Add(false);
                autoIncrement.Add(false);
            }

            try
            {
                DataTable schema = reader.GetSchemaTable();
                if (schema == null)
                    return;
                bool hasReadOnly = schema.Columns.Contains("IsReadOnly");
                bool hasAuto = schema.Columns.Contains("IsAutoIncrement");
                if (!hasReadOnly && !hasAuto)
                    return;
                for (int i = 0; i < reader.FieldCount && i < schema.Rows.Count; i++)
                {
                    DataRow row = schema.Rows[i];
                    if (hasReadOnly && row["IsReadOnly"] is bool isReadOnly)
                        readOnly[i] = isReadOnly;
                    if (hasAuto && row["IsAutoIncrement"] is bool isAuto)
                        autoIncrement[i] = isAuto;
                }
            }
            catch (NotSupportedException)
            {
                // The provider has no schema table; the defaults above are the answer.
            }
        }

        // Qt calls rowCount()/columnCount() with a default-constructed (invalid) QModelIndex for
        // the root, not with null; a valid parent means "child of a cell", which this flat model
        // does not have.
        public override int RowCount(QModelIndex parent = default)
            => !parent.IsValid() ? rows.Count : 0;

        public override int ColumnCount(QModelIndex parent = default)
            => !parent.IsValid() ? columns.Count : 0;

        public override object Data(QModelIndex index, int role = default)
        {
            // Qt::DisplayRole is 0 and Qt::EditRole is 2; Qt's QSqlQueryModel serves both from the
            // record. EditRole matters in a view: the delegate reads it to seed the editor, so a
            // model that answers only DisplayRole opens every editor empty and writes that empty
            // value back when the edit ends.
            if ((role != 0 && role != 2) || !index.IsValid())
                return null;
            return CellValue(index.Row(), index.Column());
        }

        /// <summary>The cell as Qt sees it; a subclass may overlay pending edits.</summary>
        protected virtual object CellValue(int row, int column)
            => Normalize(RawCell(row, column));

        /// <summary>
        /// A database value as a QtNative value: null/DB null is the invalid QVariant, and the
        /// types Qt has no metatype for take the closest one it does (decimal is a double,
        /// DateTimeOffset keeps its wall clock, TimeSpan is its string form).
        /// </summary>
        protected static object Normalize(object value)
        {
            if (value == null || value == DBNull.Value)
                return null;
            switch (value)
            {
                case decimal decimalValue: return (double)decimalValue;
                case DateTimeOffset offset: return offset.DateTime;
                case TimeSpan time: return time.ToString();
                default: return value;
            }
        }

        /// <summary>The cell's value as ADO.NET handed it over.</summary>
        protected object RawCell(int row, int column)
        {
            if (row < 0 || row >= rows.Count || column < 0 || column >= columns.Count)
                return null;
            return rows[row][column];
        }

        public override object HeaderData(int section, Qt.Orientation orientation, int role = default)
        {
            if (orientation == Qt.Orientation.Horizontal)
            {
                // A stored header wins; a DisplayRole lookup falls back to the stored EditRole
                // value, which is how Qt's QSqlQueryModel lets an EditRole rename show in the view.
                if (section >= 0 && section < headers.Count)
                {
                    var stored = headers[section];
                    if (stored.TryGetValue(role, out object value) && value != null)
                        return value;
                    if (role == 0 && stored.TryGetValue(2, out object editValue) && editValue != null)
                        return editValue;
                }
                if (role == 0 && section >= 0 && section < columns.Count)
                    return columns[section];
                return null;
            }
            if (role == 0 && section >= 0 && section < rows.Count)
                return section + 1;
            return null;
        }

        /// <summary>
        /// Stores a horizontal header value for a role, the way Qt's QSqlQueryModel does, and emits
        /// <c>headerDataChanged</c>. A null value removes the override again.
        /// </summary>
        public override bool SetHeaderData(int section, Qt.Orientation orientation, object value,
            int role = default)
        {
            if (orientation != Qt.Orientation.Horizontal || section < 0 || section >= columns.Count)
                return false;

            while (headers.Count <= section)
                headers.Add(new Dictionary<int, object>());
            if (value == null)
                headers[section].Remove(role);
            else
                headers[section][role] = value;

            HeaderDataChangedSignal.Emit(Qt.Orientation.Horizontal, section, section);
            return true;
        }

        /// <summary>The value of one cell, by column name, as the model sees it.</summary>
        public object Value(int row, string columnName)
        {
            int column = ColumnIndex(columnName);
            return column < 0 ? null : CellValue(row, column);
        }

        /// <summary>
        /// A row as a plain dictionary (the counterpart of QSqlRecord), read through the model so
        /// a subclass's staged edits are visible here the way Qt's record() reads data(EditRole).
        /// </summary>
        public IReadOnlyDictionary<string, object> Record(int row)
        {
            var result = new Dictionary<string, object>(columns.Count, StringComparer.Ordinal);
            for (int i = 0; i < columns.Count; i++)
                result[columns[i]] = CellValue(row, i);
            return result;
        }
    }
}
